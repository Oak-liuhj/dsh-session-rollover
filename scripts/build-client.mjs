/** 无构建依赖：将独立 UI factory 嵌入 ModuleLoader 模板，保留既有 toast API。 */
import {readFileSync, writeFileSync} from 'node:fs';
const root = new URL('../', import.meta.url);
const template = readFileSync(new URL('src/client/toast-client.js', root), 'utf8');
const ui = readFileSync(new URL('src/client/rollover-ui.js', root), 'utf8').replace('export function createRolloverUI', 'function createRolloverUI');
const {version} = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
const output = `// Generated by npm run build; edit src/client/. Version ${version}.\n` + template.replace('            function apply(ctx) {',
    ui + '\n            function apply(ctx) {\n                try { createRolloverUI(require("react")).apply(ctx); } catch (e) { debug(e); }');
const path = new URL('client.js', root);
if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== output) throw new Error('client.js is stale; run npm run build');
} else writeFileSync(path, output);
